#include "core/ConfigGen.hpp"

#include <QJsonArray>

ConfigGen::ConfigGen(const LxPaths &paths)
    : m_paths(paths)
{
}

QString ConfigGen::dnsmasq(const QJsonObject &dhcp, const QJsonArray &reservations,
                           const QString &listenNic, const QString &serverIp) const
{
    QString s;
    s += QStringLiteral("# generated by lxboot — do not edit\n");
    s += QStringLiteral("port=0\n");
    s += QStringLiteral("bind-interfaces\n");
    s += QStringLiteral("except-interface=lo\n");
    if (!listenNic.isEmpty())
        s += QStringLiteral("interface=%1\n").arg(listenNic);
    s += QStringLiteral("dhcp-leasefile=%1/dnsmasq.leases\n").arg(m_paths.prefix);
    s += QStringLiteral("dhcp-script=%1\n").arg(m_paths.hook);
    s += QStringLiteral("enable-tftp\n");
    s += QStringLiteral("tftp-root=%1\n").arg(m_paths.tftp);
    s += QStringLiteral("log-dhcp\n");
    s += QStringLiteral("dhcp-authoritative\n");

    const QString start = dhcp.value(QStringLiteral("pool_start")).toString();
    const QString end = dhcp.value(QStringLiteral("pool_end")).toString();
    const int lease = dhcp.value(QStringLiteral("lease_time")).toInt(3600);
    s += QStringLiteral("dhcp-range=%1,%2,%3s\n").arg(start, end, QString::number(lease));
    const QString mask = dhcp.value(QStringLiteral("netmask")).toString(QStringLiteral("255.255.255.0"));
    const QString gw = dhcp.value(QStringLiteral("gateway")).toString(serverIp);
    const QString dns = dhcp.value(QStringLiteral("dns")).toString(QStringLiteral("8.8.8.8"));
    s += QStringLiteral("dhcp-option=1,%1\n").arg(mask);
    s += QStringLiteral("dhcp-option=3,%1\n").arg(gw);
    s += QStringLiteral("dhcp-option=6,%1\n").arg(dns);
    s += QStringLiteral("dhcp-option=66,%1\n").arg(serverIp);
    s += QStringLiteral("dhcp-match=set:efi-x86_64,option:client-arch,7\n");
    s += QStringLiteral("dhcp-match=set:efi-x86_64,option:client-arch,9\n");
    s += QStringLiteral("dhcp-boot=tag:efi-x86_64,ipxe.efi\n");
    s += QStringLiteral("dhcp-boot=undionly.kpxe\n");
    s += QStringLiteral("pxe-service=x86PC,\"LXBoot\",undionly.kpxe\n");
    s += QStringLiteral("pxe-service=X86-64_EFI,\"LXBoot UEFI\",ipxe.efi\n");

    for (const auto &v : reservations) {
        const auto c = v.toObject();
        const QString mac = c.value(QStringLiteral("mac")).toString();
        const QString ip = c.value(QStringLiteral("ip")).toString();
        const QString host = c.value(QStringLiteral("hostname")).toString(QStringLiteral("pc"));
        if (mac.isEmpty() || ip.isEmpty())
            continue;
        s += QStringLiteral("dhcp-host=%1,%2,%3\n").arg(mac, ip, host);
    }
    return s;
}

QString ConfigGen::ipxeScript(const QString &serverIp) const
{
    return QStringLiteral(
               "#!ipxe\n"
               "set initiator-iqn iqn.2026-11.lxboot.client:${net0/mac}\n"
               "isset ${mac} || set mac ${net0/mac}\n"
               "echo LXBoot diskless ${mac}\n"
               "set keep-san 1\n"
               "sanhook iscsi:%1::::iqn.2026-11.lxboot:client-${mac:hexhyp}\n"
               "sanboot iscsi:%1::::iqn.2026-11.lxboot:client-${mac:hexhyp} || sanboot --no-describe --drive 0x80\n"
               "shell\n")
        .arg(serverIp);
}

QString ConfigGen::dhcpHook() const
{
    return QStringLiteral(
        "#!/bin/sh\n"
        "export LXBOOT_PREFIX=\"%1\"\n"
        "export LXBOOT_SOCK=\"%2\"\n"
        "exec /usr/bin/lxboot lease \"$1\" \"$2\" \"$3\" \"$4\"\n");
}

QString ConfigGen::netdevBond(const QString &name, const QStringList &slaves) const
{
    QString s = QStringLiteral("[NetDev]\nName=%1\nKind=bond\n\n[Bond]\nMode=802.3ad\nTransmitHashPolicy=layer3+4\nLACPTransmitRate=fast\nMIIMonitorSec=1s\n")
                    .arg(name);
    Q_UNUSED(slaves);
    return s;
}

QString ConfigGen::networkd(const QString &iface, const QString &ip, const QString &mask,
                            const QString &gw, const QString &dns) const
{
    int prefix = 24;
    if (mask == QLatin1String("255.255.0.0"))
        prefix = 16;
    else if (mask == QLatin1String("255.0.0.0"))
        prefix = 8;
    else if (mask == QLatin1String("255.255.255.128"))
        prefix = 25;
    QString s;
    s += QStringLiteral("[Match]\nName=%1\n\n").arg(iface);
    s += QStringLiteral("[Network]\nAddress=%1/%2\n").arg(ip, QString::number(prefix));
    if (!gw.isEmpty())
        s += QStringLiteral("Gateway=%1\n").arg(gw);
    if (!dns.isEmpty())
        s += QStringLiteral("DNS=%1\n").arg(dns);
    return s;
}
